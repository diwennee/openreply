#!/bin/sh
# Writes .env for docker-compose.prod.yml from AWS SSM Parameter Store.
#
#   AWS_REGION=us-east-1 sh deploy/render-env.sh /openreply/prod [/openreply/prod-db-ca]
#
# Every parameter under the prefix becomes KEY=VALUE (the last path segment is
# the key), so app settings such as NEXTAUTH_URL, REDIS_URL, RESEND_API_KEY or
# INSTAGRAM_APP_SECRET are simply stored there under their env var names.
#
# DATABASE_URL and MIGRATE_DATABASE_URL are assembled from these, as created
# alongside deploy/postgres-roles.sql:
#   DB_HOST DB_NAME DB_SCHEMA DB_USER DB_PASSWORD DB_MIGRATION_USER DB_MIGRATION_PASSWORD
#   DB_PORT (optional, 5432)
#
# The optional second argument is a parameter holding the Postgres server's CA
# certificate; it is written to certs/db-ca.crt for verified TLS.
#
# Needs the AWS CLI and, on the host's instance role, ssm:GetParametersByPath
# on the prefix (plus ssm:GetParameter on the CA parameter) and kms:Decrypt.
# The .env is written with mode 600 and never printed.

set -eu

PREFIX="${1:?usage: render-env.sh <ssm-prefix> [ca-cert-parameter]}"
CA_PARAM="${2:-}"
REGION="${AWS_REGION:-${AWS_DEFAULT_REGION:?set AWS_REGION to the region of the parameters}}"
cd "$(dirname "$0")/.."

umask 077
TMP=$(mktemp .env.XXXXXX)
trap 'rm -f "$TMP"' EXIT

aws ssm get-parameters-by-path --region "$REGION" --path "$PREFIX" --recursive \
  --with-decryption --query 'Parameters[].[Name,Value]' --output text > "$TMP"

if [ ! -s "$TMP" ]; then
  echo "render-env: nothing under $PREFIX" >&2
  exit 1
fi

get() { awk -F '\t' -v k="$1" '{ n = $1; sub(/.*\//, "", n) } n == k { print $2; exit }' "$TMP"; }

if grep -q "'" "$TMP"; then
  echo "render-env: a value contains a single quote, which .env cannot hold as written here" >&2
  exit 1
fi

OUT=$(mktemp .env.out.XXXXXX)
{
  echo "# Generated by deploy/render-env.sh from $PREFIX on $(date -u '+%Y-%m-%d %H:%M UTC'). Do not edit; edit SSM."
  # Single quotes: docker compose takes the value literally (no $ interpolation).
  awk -F '\t' '{ n = $1; sub(/.*\//, "", n); printf "%s='\''%s'\''\n", n, $2 }' "$TMP"

  host=$(get DB_HOST); db=$(get DB_NAME); schema=$(get DB_SCHEMA); port=$(get DB_PORT)
  port="${port:-5432}"
  if [ -n "$host" ] && [ -n "$db" ]; then
    q="schema=${schema:-public}"
    if [ -n "$CA_PARAM" ]; then
      # pg (the app) and Prisma's migration engine name the TLS options differently.
      app_tls="&sslmode=verify-full&sslrootcert=/certs/db-ca.crt"
      mig_tls="&sslmode=require&sslcert=/certs/db-ca.crt&sslaccept=strict"
      echo "DB_CA_FILE='./certs/db-ca.crt'"
    else
      app_tls=""; mig_tls=""
    fi
    echo "DATABASE_URL='postgresql://$(get DB_USER):$(get DB_PASSWORD)@$host:$port/$db?$q$app_tls'"
    mu=$(get DB_MIGRATION_USER)
    if [ -n "$mu" ]; then
      echo "MIGRATE_DATABASE_URL='postgresql://$mu:$(get DB_MIGRATION_PASSWORD)@$host:$port/$db?$q$mig_tls'"
    fi
  fi
} > "$OUT"

if [ -n "$CA_PARAM" ]; then
  mkdir -p certs
  aws ssm get-parameter --region "$REGION" --name "$CA_PARAM" --query Parameter.Value --output text > certs/db-ca.crt
  chmod 644 certs/db-ca.crt
fi

mv "$OUT" .env
chmod 600 .env

missing=""
for k in DATABASE_URL REDIS_URL NEXTAUTH_URL NEXTAUTH_SECRET ENCRYPTION_KEY CRON_SECRET OPENREPLY_DOMAIN; do
  grep -q "^$k=" .env || missing="$missing $k"
done
echo "render-env: wrote .env ($(grep -c '=' .env) entries)"
[ -z "$missing" ] || echo "render-env: still missing:$missing" >&2
